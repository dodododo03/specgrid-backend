function page(eyebrow, title, intro, body) {
  const el = section("page-wrap workspace legal-page");
  el.innerHTML = `
    <article class="panel legal">
      <p class="eyebrow">${eyebrow}</p>
      <h1>${title}</h1>
      <p class="muted">${intro}</p>
      ${body}
    </article>`;
  // in-page table of contents links (#/privacy uses the hash for routing, so scroll manually)
  el.addEventListener("click", (e) => {
    const a = e.target.closest("[data-jump]");
    if (!a) return;
    e.preventDefault();
    el.querySelector(`#${a.dataset.jump}`)?.scrollIntoView({ behavior: "smooth", block: "start" });
  });
  return { el };
}

function toc(items) {
  return `<nav class="legal-toc" aria-label="목차"><ol>${items
    .map(([id, t]) => `<li><a href="#" data-jump="${id}">${t}</a></li>`)
    .join("")}</ol></nav>`;
}

